    let animatedROI = {
        annualPaperCost: 9700,
        annualKimemCost: 3950,
        savingsPerYear: 7725,
        treesSaved: 2.0,
    };

    function initROICalculator() {
        const empInput = document.getElementById('roiEmployees');
        const empVal = document.getElementById('roiEmpVal');
        const printInput = document.getElementById('roiPrintCost');
        const kimemInput = document.getElementById('roiKimemPrice');

        if (!empInput || !printInput || !kimemInput) return;

        const updateROI = () => {
            const employees = Math.min(500, Math.max(1, Number(empInput.value) || 1));
            const printCost = Math.max(0, Number(printInput.value) || 0);
            const kimemPrice = Math.max(0, Number(kimemPriceVal() || 0));

            if (empVal) empVal.textContent = employees;

            const annualPaperCost = employees * printCost;
            const annualKimemCost = employees * kimemPrice;
            const savingsPerYear = Math.max(0, annualPaperCost - annualKimemCost / 2);
            const treesSaved = employees * 0.04;

            animateNumber('resPaperCost', animatedROI.annualPaperCost, annualPaperCost, (v) => formatUSD(v));
            animateNumber('resKimemCost', animatedROI.annualKimemCost, annualKimemCost, (v) => formatUSD(v));
            animateNumber('resSavings', animatedROI.savingsPerYear, savingsPerYear, (v) => formatUSD(v));
            animateNumber('resTrees', animatedROI.treesSaved, treesSaved, (v) => Number(v).toFixed(2));

            animatedROI = { annualPaperCost, annualKimemCost, savingsPerYear, treesSaved };
        };

        function kimemPriceVal() {
            return Number(kimemInput.value) || 0;
        }

        empInput.addEventListener('input', updateROI);
        printInput.addEventListener('input', updateROI);
        kimemInput.addEventListener('input', updateROI);

        updateROI();
    }

    function formatUSD(val) {
        return new Intl.NumberFormat('en-US', {
            style: 'currency',
            currency: 'USD',
            maximumFractionDigits: 0,
        }).format(Number(val) || 0);
    }

    function animateNumber(elementId, start, end, formatFn) {
        const el = document.getElementById(elementId);
        if (!el) return;

        const duration = 300;
        const startTime = performance.now();
        const diff = end - start;

        const step = (now) => {
            const progress = Math.min(1, (now - startTime) / duration);
            const eased = 1 - Math.pow(1 - progress, 3);
            const current = start + diff * eased;
            el.textContent = formatFn(current);
            if (progress < 1) requestAnimationFrame(step);
        };
        requestAnimationFrame(step);
    }

