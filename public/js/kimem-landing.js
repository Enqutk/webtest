    let currentLocale = 'en';
    const STORAGE_KEY = 'kimem_locale';

    // State
    let shimmerX = 50;
    let shimmerY = 50;
    let sceneShiftY = 0;
    let sceneShiftZ = 0;
    let sceneOpacity = 1;
