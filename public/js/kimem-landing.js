    function renderTestimonial(index) {
        const copy = LANDING_LOCALIZATION[currentLocale] || LANDING_LOCALIZATION.en;
        const items = copy.testimonials.items;
        activeQuoteIndex = index % items.length;
        const item = items[activeQuoteIndex];

        const textEl = document.getElementById('testQuoteText');
        const authorEl = document.getElementById('testQuoteAuthor');
        const roleEl = document.getElementById('testQuoteRole');
        const dotsContainer = document.getElementById('testDots');

        if (textEl) textEl.textContent = `"${item.text}"`;
        if (authorEl) authorEl.textContent = item.name;
        if (roleEl) roleEl.textContent = item.role;

        if (dotsContainer) {
            dotsContainer.innerHTML = items
                .map(
                    (_, i) =>
                        `<button type="button" class="${i === activeQuoteIndex ? 'active' : ''}" data-index="${i}"></button>`
                )
                .join('');

            dotsContainer.querySelectorAll('button').forEach((btn) => {
                btn.addEventListener('click', () => {
                    const idx = Number(btn.getAttribute('data-index'));
                    renderTestimonial(idx);
                });
            });
        }
    }

