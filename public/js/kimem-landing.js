    // 3D Card tilt and shine
    function updateCard3D() {
        if (!cardScene || !cardFront || !cardBack) return;

        const isMobile = window.innerWidth < 768;
        const maxTilt = isMobile ? 14 : 35;

        stackRotateX = clamp(((shimmerY - 50) / 50) * -maxTilt, -maxTilt, maxTilt);
        stackRotateY = clamp(((shimmerX - 50) / 50) * maxTilt, -maxTilt, maxTilt);

        cardScene.style.transform = `translate3d(0, ${sceneShiftY}px, ${sceneShiftZ}px) rotateX(${stackRotateX}deg) rotateY(${stackRotateY}deg)`;
        cardScene.style.opacity = sceneOpacity;

        cardFront.style.transform = `translate3d(0, 0, 26px)`;
        cardFront.style.setProperty('--shine-x', `${shimmerX}%`);
        cardFront.style.setProperty('--shine-y', `${shimmerY}%`);

        cardBack.style.transform = `translate3d(-20px, -14px, -60px) rotateX(${(-stackRotateX * 0.42).toFixed(2)}deg) rotateY(${(-stackRotateY * 0.42).toFixed(2)}deg)`;
        cardBack.style.setProperty('--shine-x', `${shimmerX}%`);
        cardBack.style.setProperty('--shine-y', `${shimmerY}%`);
    }

    function initHeroCardInteractions() {
        if (!heroRef) return;

        heroRef.addEventListener('mousemove', (e) => {
            const rect = heroRef.getBoundingClientRect();
            shimmerX = clamp(((e.clientX - rect.left) / rect.width) * 100, 0, 100);
            shimmerY = clamp(((e.clientY - rect.top) / rect.height) * 100, 0, 100);
            updateCard3D();
        });

        heroRef.addEventListener('mouseleave', () => {
            shimmerX = 50;
            shimmerY = 50;
            updateCard3D();
        });

        const cardStage = document.getElementById('cardStage');
        if (cardStage) {
            cardStage.addEventListener('click', triggerCardSpin);
            cardStage.addEventListener('keyup', (e) => {
                if (e.key === 'Enter') triggerCardSpin();
            });
        }
    }

    function triggerCardSpin() {
        if (isShowcasing) return;
        isShowcasing = true;

        frontFlipY += 360;
        if (cardShell) {
            cardShell.style.transition = 'transform 1.3s cubic-bezier(0.25, 1, 0.5, 1)';
            cardShell.style.transform = `rotateY(${frontFlipY}deg)`;
        }

        setTimeout(() => {
            isShowcasing = false;
        }, 1350);
    }

    // Scroll parallax & header
    function initScroll() {
        const onScroll = () => {
            if (topNav) {
                topNav.classList.toggle('scrolled', window.scrollY > 24);
            }

            if (heroRef) {
                const rect = heroRef.getBoundingClientRect();
                const progress = clamp((window.innerHeight - rect.top) / (window.innerHeight + rect.height), 0, 1);
                sceneShiftY = progress * 40;
                sceneShiftZ = progress * -160;
                sceneOpacity = 1 - progress * 0.2;
                updateCard3D();
            }

            document.querySelectorAll('.section-shell').forEach((section, index) => {
                const rect = section.getBoundingClientRect();
                const progress = clamp((window.innerHeight - rect.top) / (window.innerHeight + rect.height), 0, 1);
                const dir = index % 2 === 0 ? 1 : -1;
                section.style.setProperty('--parallax-y', `${(progress - 0.5) * 18 * dir}px`);
            });
        };

        window.addEventListener('scroll', onScroll, { passive: true });
        onScroll();
    }

    // Reveal on scroll
    let revealObserver = null;
    function observeReveals() {
        if (!('IntersectionObserver' in window)) {
            document.querySelectorAll('.reveal').forEach((el) => el.classList.add('visible'));
            return;
        }

        if (revealObserver) revealObserver.disconnect();

        revealObserver = new IntersectionObserver(
            (entries) => {
                entries.forEach((entry) => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('visible');
                    }
                });
            },
            { threshold: 0.12 }
        );

        document.querySelectorAll('.reveal').forEach((el) => revealObserver.observe(el));
    }

